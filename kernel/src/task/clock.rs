//! Задача обновления часов на панели задач. Не перерисовывает весь экран —
//! только помечает часы "грязными" для следующего flush.

use super::sleep::Sleep;

/// Задача: раз в секунду генерирует событие для UI.
/// Не имеет доступа к Writer напрямую — сообщает через флаг.
pub async fn clock_task() {
    loop {
        Sleep::new_ms(1000).await;
        crate::interrupts::clock_tick();
    }
}