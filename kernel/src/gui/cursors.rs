//! Курсоры: разные формы для разных контекстов.

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum CursorKind {
    Arrow,
    IBeam,
    ResizeNS,
    ResizeEW,
    ResizeNWSE,
    ResizeNESW,
}

pub fn size(k: CursorKind) -> (i32, i32) {
    match k {
        CursorKind::Arrow => (12, 19),
        CursorKind::IBeam => (11, 17),
        CursorKind::ResizeNS | CursorKind::ResizeEW => (16, 16),
        CursorKind::ResizeNWSE | CursorKind::ResizeNESW => (16, 16),
    }
}

pub fn bitmap(k: CursorKind) -> &'static [(i32, i32, u8)] {
    match k {
        CursorKind::Arrow => ARROW,
        CursorKind::IBeam => IBEAM,
        CursorKind::ResizeNS => RESIZE_NS,
        CursorKind::ResizeEW => RESIZE_EW,
        CursorKind::ResizeNWSE => RESIZE_NWSE,
        CursorKind::ResizeNESW => RESIZE_NESW,
    }
}

